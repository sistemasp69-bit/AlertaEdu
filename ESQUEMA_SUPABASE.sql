CREATE TABLE IF NOT EXISTS public.students (
 id text PRIMARY KEY, nombre text NOT NULL, carrera text NOT NULL,
 semestre integer NOT NULL, promedio double precision NOT NULL,
 asistencia double precision NOT NULL, riesgo text NOT NULL,
 estado text NOT NULL, materias text NOT NULL
);
CREATE TABLE IF NOT EXISTS public.followups (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id text NOT NULL REFERENCES public.students(id),
 tipo text NOT NULL, responsable text NOT NULL, nota text NOT NULL, fecha text NOT NULL
);
CREATE TABLE IF NOT EXISTS public.evaluations (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id text NOT NULL REFERENCES public.students(id),
 promedio double precision NOT NULL, asistencia double precision NOT NULL,
 reprobadas integer NOT NULL, puntos integer NOT NULL, max_puntos integer NOT NULL,
 nivel text NOT NULL, metodo text NOT NULL, fecha text NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_evaluations_student ON public.evaluations(student_id,id DESC);
CREATE TABLE IF NOT EXISTS public.users (
 username text PRIMARY KEY, password_hash text NOT NULL, salt text NOT NULL,
 role text NOT NULL, active integer NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS public.sessions (
 token_hash text PRIMARY KEY, username text NOT NULL REFERENCES public.users(username),
 csrf_token text NOT NULL, expires integer NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_sessions_expires ON public.sessions(expires);
CREATE TABLE IF NOT EXISTS public.ml_predictions (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id text NOT NULL REFERENCES public.students(id),
 probability double precision NOT NULL CHECK (probability BETWEEN 0 AND 1),
 level text NOT NULL, model_version text NOT NULL, date text NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ml_student ON public.ml_predictions(student_id,id DESC);
CREATE TABLE IF NOT EXISTS public.risk_settings (
 id integer PRIMARY KEY CHECK (id=1), medium_points integer NOT NULL,
 high_points integer NOT NULL, notify_points integer NOT NULL, updated_at text NOT NULL
);
INSERT INTO public.risk_settings(id,medium_points,high_points,notify_points,updated_at)
 VALUES (1,3,6,7,'inicial') ON CONFLICT(id) DO NOTHING;
CREATE TABLE IF NOT EXISTS public.academic_alerts (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id text NOT NULL REFERENCES public.students(id),
 old_level text NOT NULL, new_level text NOT NULL,
 previous_points integer NOT NULL, new_points integer NOT NULL,
 reason text NOT NULL, estado text NOT NULL DEFAULT 'Nueva',
 responsable text NOT NULL DEFAULT '', created_at text NOT NULL, updated_at text NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_academic_alerts_student ON public.academic_alerts(student_id,id DESC);
CREATE INDEX IF NOT EXISTS idx_academic_alerts_state ON public.academic_alerts(estado,id DESC);
CREATE TABLE IF NOT EXISTS public.academic_alert_events (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 alert_id integer NOT NULL REFERENCES public.academic_alerts(id),
 actor text NOT NULL, action text NOT NULL, detail text NOT NULL, created_at text NOT NULL
);
CREATE TABLE IF NOT EXISTS public.gmail_verified_emails (
 username text PRIMARY KEY REFERENCES public.users(username),
 email text NOT NULL UNIQUE, verified_at integer NOT NULL
);
CREATE TABLE IF NOT EXISTS public.gmail_pending_emails (
 username text PRIMARY KEY REFERENCES public.users(username),
 email text NOT NULL, token_hash text NOT NULL UNIQUE, expires_at integer NOT NULL
);
CREATE TABLE IF NOT EXISTS public.gmail_reset_tokens (
 username text PRIMARY KEY REFERENCES public.users(username),
 token_hash text NOT NULL UNIQUE, password_hash_at_issue text NOT NULL,
 expires_at integer NOT NULL
);
CREATE TABLE IF NOT EXISTS public.gmail_request_attempts (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 action text NOT NULL, address_digest text NOT NULL, ip_digest text NOT NULL, ts integer NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_gmail_attempts_ts ON public.gmail_request_attempts(ts);
CREATE INDEX IF NOT EXISTS idx_gmail_attempts_address ON public.gmail_request_attempts(action,address_digest,ts);

-- RLS está activada por defecto para todas las tablas de la aplicación.
DO $$
DECLARE t text;
BEGIN
 FOR t IN SELECT unnest(ARRAY['students','followups','evaluations','users','sessions',
  'ml_predictions','risk_settings','academic_alerts','academic_alert_events',
  'gmail_verified_emails','gmail_pending_emails','gmail_reset_tokens','gmail_request_attempts']) LOOP
  EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',t);
  EXECUTE format('REVOKE ALL ON TABLE public.%I FROM anon, authenticated',t);
 END LOOP;
END $$;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated;
