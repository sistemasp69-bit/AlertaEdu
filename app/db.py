"""PostgreSQL (Supabase) connection adapter for existing AlertaEdu queries.
No SQLite fallback: DATABASE_URL is required.
"""
import os
import re
from pathlib import Path
from contextlib import contextmanager
from dotenv import load_dotenv

# También carga .env cuando se importa app.db sin pasar por app.main.
# En Render, las variables de entorno reales tienen prioridad sobre el .env local.
load_dotenv(Path(__file__).resolve().parent.parent / ".env", override=False)
import psycopg
from psycopg import errors
from psycopg.rows import dict_row

IntegrityError = psycopg.IntegrityError

class Row(dict):
    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)

class Cursor:
    def __init__(self, raw, lastrowid=None):
        self.raw = raw
        self.lastrowid = lastrowid
        self.rowcount = raw.rowcount
    def fetchone(self):
        r = self.raw.fetchone()
        return Row(r) if r is not None else None
    def fetchall(self):
        return [Row(x) for x in self.raw.fetchall()]
    def __iter__(self):
        for r in self.raw:
            yield Row(r)

class Connection:
    def __init__(self):
        url=os.environ.get('DATABASE_URL','').strip()
        from urllib.parse import urlsplit, unquote
        passwd = unquote(urlsplit(url).password or '') if url.startswith(('postgresql://', 'postgres://')) else ''
        placeholder = any(k in passwd.upper() for k in ('YOUR-', 'YOUR_', 'PON_', 'PASSWORD]', 'CONTRASEÑA', 'CONTRASENA'))
        if not url or not passwd or placeholder:
            raise RuntimeError('DATABASE_URL no tiene una contraseña PostgreSQL real. Ejecuta CONFIGURAR_WINDOWS.bat y luego VERIFICAR_CONEXION.py; no compartas la clave en el chat.')
        if not url.startswith(('postgresql://','postgres://')):
            raise RuntimeError('DATABASE_URL debe ser una URL PostgreSQL')
        self.raw=psycopg.connect(url, sslmode='require', prepare_threshold=None, row_factory=dict_row)
        self.row_factory=Row
    def execute(self,sql,params=None):
        s=sql.strip()
        if re.match(r'^BEGIN\s+IMMEDIATE\s*;?$',s,re.I):
            return Cursor(self.raw.execute('SELECT 1 WHERE FALSE'))
        s=re.sub(r'\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b','INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',s,flags=re.I)
        s=re.sub(r'\bINSERT\s+OR\s+IGNORE\s+INTO\b','INSERT INTO',s,flags=re.I)
        ignore=bool(re.search(r'^INSERT\s+OR\s+IGNORE\s+INTO\b',sql.strip(),re.I))
        s=re.sub(r'\s+COLLATE\s+NOCASE\b','',s,flags=re.I)
        if ignore: s=s.rstrip().rstrip(';')+' ON CONFLICT DO NOTHING'
        # SQL from trusted source files only; arguments always parameterized.
        s=s.replace('?', '%s')
        m=re.match(r'^INSERT\s+INTO\s+(followups|evaluations|ml_predictions|academic_alerts|academic_alert_events|gmail_request_attempts)\b',s,re.I)
        returning=bool(m) and 'RETURNING' not in s.upper()
        if returning: s=s.rstrip().rstrip(';')+' RETURNING id'
        raw=self.raw.execute(s, params or ())
        lastid=raw.fetchone()['id'] if returning else None
        return Cursor(raw,lastid)
    def executemany(self,sql,items):
        s=sql.replace('?','%s')
        with self.raw.cursor() as c: c.executemany(s,items)
    def executescript(self,script):
        # Schema DDL contains no procedural blocks or user data.
        for stmt in script.split(';'):
            if stmt.strip(): self.execute(stmt)
    def commit(self): self.raw.commit()
    def rollback(self): self.raw.rollback()
    def close(self): self.raw.close()
    def __enter__(self): return self
    def __exit__(self,typ,val,tb):
        try:
            if typ: self.raw.rollback()
            else: self.raw.commit()
        finally: self.close()

def connect(*args,**kwargs):
    return Connection()

@contextmanager
def transaction():
    with connect() as c:
        yield c
